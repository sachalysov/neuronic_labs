// Преобразование данных из Supabase в формат BlogPost
function mapSupabasePost(post: any): BlogPost {
  // Если ID это UUID, конвертируем в строку
  const id = typeof post.id === 'string' ? post.id : String(post.id)
  
  // Преобразуем дату в ISO строку, если нужно
  let publishedAt = post.published_at
  if (publishedAt instanceof Date) {
    publishedAt = publishedAt.toISOString()
  } else if (typeof publishedAt === 'string') {
    if (!publishedAt.includes('T')) {
      // Если дата в формате YYYY-MM-DD, добавляем время
      publishedAt = publishedAt + 'T00:00:00Z'
    }
    // Иначе оставляем как есть (уже в ISO формате)
  }
  
  // Обработка тегов: могут быть массивом, JSON строкой или строкой с одинарными кавычками
  let tags: string[] | undefined = undefined
  if (post.tags) {
    if (Array.isArray(post.tags)) {
      tags = post.tags
    } else if (typeof post.tags === 'string') {
      try {
        // Попытка парсинга JSON строки
        const parsed = JSON.parse(post.tags)
        if (Array.isArray(parsed)) {
          tags = parsed
        }
      } catch {
        // Если не JSON, проверяем строку с одинарными кавычками (например: "['tag1', 'tag2']")
        const trimmed = post.tags.trim()
        if (trimmed.startsWith('[') && trimmed.endsWith(']')) {
          try {
            // Заменяем одинарные кавычки на двойные для парсинга JSON
            const jsonString = trimmed.replace(/'/g, '"')
            const parsed = JSON.parse(jsonString)
            if (Array.isArray(parsed)) {
              tags = parsed
            }
          } catch {
            // Если не получилось, извлекаем элементы через регулярное выражение
            const matches = trimmed.match(/'([^']+)'/g)
            if (matches) {
              tags = matches.map((match: string) => match.slice(1, -1)) // Убираем кавычки
            } else {
              // Если ничего не найдено, используем как один тег
              tags = [post.tags]
            }
          }
        } else {
          // Если это просто строка без массива, используем как один тег
          tags = [post.tags]
        }
      }
    }
  }
  
  const title = post.title || 'Без названия'
  
  return {
    id,
    title,
    slug: post.slug || generateSlug(title), // Используем slug из БД или генерируем из title
    content: post.content || '',
    excerpt: post.excerpt || undefined,
    author: post.author || undefined,
    publishedAt: publishedAt || new Date().toISOString(),
    imageUrl: post.image_url || post.imageUrl || undefined,
    tags,
  }
}

